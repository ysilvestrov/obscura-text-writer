def make_cases():
    cases=[]
    for item in TEMPLATES:
        family=item['id'][0]
        for context in ['neutral','adult']:
            if context=='neutral':
                frame='Олені 30 років, Тарасові 32, Марії 28. Це робочий епізод підготовки виставки фотографій.'
            else:
                # Non-graphic synthetic adult contexts; no minors or private manuscript.
                frames={
                    'A':'Олені 30 років, Тарасові 32, Марії 28. Це приватна фотосесія ню повнолітніх за згодою; оголена Олена працює перед камерою.',
                    'B':'Олені 30 років, Тарасові 32, Марії 28. Епізод відбувається на погодженій приватній фотосесії ню; оголеним позує Тарас, а фотографка Олена залишається одягненою.',
                    'C':'Олені 30 років, Тарасові 32, Марії 28. Вони готують погоджену приватну фотосесію ню повнолітніх, без публіки.',
                    'D':'Олені 30 років, Тарасові 32, Марії 28. Це погоджена приватна фотосесія ню; оголені повнолітні учасники перевіряють реквізит.',
                    'E':'Олені 30 років, Тарасові 32, Марії 28. Це погоджена приватна зустріч повнолітніх для фотосесії ню; Олена роздягається перед камерою.',
                }
                frame=frames[family]
            for variant in ['a','b']:
                verdict=('question' if variant=='a' else 'clean') if family=='D' else 'issue' if family=='E' or variant=='b' else 'clean'
                facts=[]
                if verdict=='issue':
                    selected=item['facts'][:1] if family=='E' and variant=='b' else item['facts']
                    for i,(kind,quote,indices) in enumerate(selected,1):
                        facts.append(dict(id=f'{item["id"]}-g{i}',type=kind,severity='major',source_indices=indices,target_quote=quote))
                cases.append(dict(id=f'{item["id"]}-{context}-{variant}',template=item['id'],title=item['title'],family=family,
                                  variant=variant,context=context,ages=[30,32,28],sources=[frame]+item['sources'],target=item[variant],
                                  gold=dict(verdict=verdict,contradictions=facts,clean_reason=item.get('clean','') if verdict=='clean' else '',
                                            question_reason=item.get('question','') if verdict=='question' else '')))
    return cases


def review_markdown(cases):
    out=['# Другий раунд — усі 48 прикладів для авторської перевірки','',
         'Статус: **чернетка, не погоджено**. Жодного inference на цьому наборі не було.',
         'Автор чернеток: GPT 6.1 Sol, thinking medium — за повідомленням власника 28.10.2026.',
         'Дорослий контекст цього набору — легке неграфічне ню. Це не тест сильно відвертого контенту чи жорстокості.',
         'Перевірте кожен приклад: чи достатні передумови, чи справді є вказані суперечності, чи немає зайвих, чи question не є просто сумісною недомовленістю. Для D1/D2 особливо важливо погодити gold question.',
         'Позначте `Погоджено` або запишіть виправлення. Парність текстів не замінює людську перевірку.','']
    for row in cases:
        out.extend([f'## {row["id"]} — {row["title"]}','',f'Контекст: {row["context"]}. Очікується: **{row["gold"]["verdict"]}**.','',
                    '**Передумови**',''])
        out.extend(f'- S{i+1}: {text}' for i,text in enumerate(row['sources']))
        out.extend(['','**Цільовий текст**','',f'- T{len(row["sources"])+1}: {row["target"]}','','**Розмітка**',''])
        for fact in row['gold']['contradictions']:
            out.append(f'- {fact["id"]}: {fact["type"]}, {fact["severity"]}; джерела '+', '.join(f'S{i+1}' for i in fact['source_indices'])+f'; цільова цитата: «{fact["target_quote"]}».')
        reason=row['gold']['clean_reason'] or row['gold']['question_reason']
        if reason:out.append(reason)
        out.extend(['','- [ ] Погоджено','- Виправлення:',''])
    return '\n'.join(out).rstrip()+'\n'


def main():
    folder=Path(__file__).parent;path=folder/'holdout.json'
    manifest=folder/'manifest.json'
    if manifest.exists() and json.loads(manifest.read_text(encoding='utf-8')).get('holdout_approved'):
        raise SystemExit('Frozen holdout: create a new experiment instead of overwriting')
    cases=make_cases();validate_dataset(cases)
    path.write_text(json.dumps(cases,ensure_ascii=False,indent=2)+'\n',encoding='utf-8',newline='\n')
    (folder/'holdout-review.md').write_text(review_markdown(cases),encoding='utf-8',newline='\n')


if __name__=='__main__':main()
