import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
const root=process.argv[2];
const {externalOriginLabel}=await import(pathToFileURL(root+'/src/storygen/web/static/external-origin.js'));
const {setLocale}=await import(pathToFileURL(root+'/src/storygen/web/static/i18n.js'));
assert.equal(externalOriginLabel(null),'');
assert.equal(externalOriginLabel({id:'v'}),'');
assert.equal(externalOriginLabel({external_origin:null}),'');
assert.equal(externalOriginLabel({external_origin:{client:'Claude Code',model:null}}),'Зовнішній клієнт: Claude Code');
assert.equal(externalOriginLabel({external_origin:{client:'Codex',model:'gpt <b>&'}}),'Зовнішній клієнт: Codex · gpt <b>&');
await setLocale('en');
assert.equal(externalOriginLabel({external_origin:{client:'Claude Code'}}),'External client: Claude Code');
assert.equal(externalOriginLabel({external_origin:{client:'Codex',model:'sonnet'}}),'External client: Codex · sonnet');
// Rendering into the status-row node: shown for an external version, hidden otherwise, relabelled on a locale switch.
const {renderOriginInto}=await import(pathToFileURL(root+'/src/storygen/web/static/external-origin.js'));
await setLocale('uk');
const node={hidden:true,textContent:''};
renderOriginInto(node,{external_origin:{client:'Codex',model:'sonnet'}});
assert.deepEqual([node.hidden,node.textContent],[false,'Зовнішній клієнт: Codex · sonnet']);
await setLocale('en');
assert.deepEqual([node.hidden,node.textContent],[false,'External client: Codex · sonnet']);
renderOriginInto(node,{id:'author-save'});
assert.deepEqual([node.hidden,node.textContent],[true,'']);
await setLocale('uk');
assert.equal(node.textContent,'');
renderOriginInto(node,{external_origin:{client:'Claude Code'}});
assert.deepEqual([node.hidden,node.textContent],[false,'Зовнішній клієнт: Claude Code']);
renderOriginInto(node,null);
assert.deepEqual([node.hidden,node.textContent],[true,'']);
renderOriginInto(null,{external_origin:{client:'Codex'}});
// R-48 MANUSCRIPT-IMPORT: prose from the author's manuscript names its file; a scene without a plan adds that the plan is
// optional (validation checks the prose and the memory). The file name is author text, never localized.
const imported={manuscript_import:{file_name:'mayak <1>.docx',file_sha256:'a'.repeat(64),imported_at:'2026-11-25T00:00:00Z'}};
assert.equal(externalOriginLabel(imported),'Імпортовано з рукопису: mayak <1>.docx');
assert.equal(externalOriginLabel(imported,{heads:{prose:'p'},beats:''}),'Імпортовано з рукопису: mayak <1>.docx · План необов’язковий: валідація перевіряє прозу й пам’ять');
assert.equal(externalOriginLabel(imported,{heads:{prose:'p',plan:'x'},beats:''}),'Імпортовано з рукопису: mayak <1>.docx');
assert.equal(externalOriginLabel(imported,{heads:{prose:'p'},beats:'Сцена 1: план'}),'Імпортовано з рукопису: mayak <1>.docx');
assert.equal(externalOriginLabel({id:'v'},{heads:{},beats:''}),'');
renderOriginInto(node,imported,{heads:{prose:'p'},beats:'  '});
assert.equal(node.hidden,false);
await setLocale('en');
assert.equal(node.textContent,'Imported from manuscript: mayak <1>.docx · Plan optional: validation checks the prose and the memory');
await setLocale('uk');
renderOriginInto(node,null);
